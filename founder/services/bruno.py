    """Подсказки о ходе беседы: что уже обсуждали и какие вопросы звучали."""
    if not messages:
        return ""
    founder_text = " ".join(m["content"] for m in messages if m["role"] == "user").lower()
    founder_turns = sum(1 for m in messages if m["role"] == "user")
    covered = [axis for axis, pattern in AXIS_HINTS.items() if re.search(pattern, founder_text)]
    missing = [axis for axis in AXIS_HINTS if axis not in covered]

    asked = []
    for message in messages[:-1]:
        if message["role"] == "assistant":
            asked.extend(q.strip() for q in QUESTION_RE.findall(message["content"]))
    asked = [q for q in asked if len(q) > 12][-6:]

    notes = [f"Ход беседы: основатель ответил {founder_turns} раз(а)."]
    if covered:
        notes.append("Уже звучало: " + ", ".join(covered) + ".")
    if missing:
        notes.append("Ещё не обсуждали: " + ", ".join(missing)
                     + ". Переходи к ним плавно, когда текущая тема исчерпана.")
    if asked:
        notes.append("Ты уже спрашивал (не повторяй дословно и по смыслу, "
                     "если ответ уже получен): " + " | ".join(asked))
    claims = [m["content"].strip()[:200] for m in messages[:-1]
              if m["role"] == "user" and CLAIM_RE.search(m["content"])][-5:]
    conflict = contradiction(messages)
    changed = number_change(messages)
    if conflict:
        notes.append("ВНИМАНИЕ, противоречие. Раньше основатель сказал: «" + conflict
                     + "». Сейчас: «" + messages[-1]["content"].strip()[:200] + "». Начни ответ "
                     "с того, что заметил расхождение, назови обе версии и спроси, какая верна. "
                     "Не радуйся новой цифре и не давай советов, пока это не прояснится.")
    elif changed:
        topic, old, new, quote = changed
        notes.append(f"ВНИМАНИЕ, цифра изменилась: раньше по теме «{topic}» основатель называл {old} "
                     f"(«{quote}»), сейчас {new}. Начни ответ с этого: назови обе цифры и уточни, это "
                     "рост за какой-то срок или поправка. Только потом совет.")
    elif claims and messages[-1]["role"] == "user":
        notes.append("Что основатель уже утверждал (сверь с новым сообщением, при "
                     "противоречии назови обе версии): «" + "» | «".join(claims) + "»")
    latest = messages[-1]["content"] if messages[-1]["role"] == "user" else ""
    from founder.services.mentor import chosen_option

    choice = chosen_option(messages)
    if choice:
        number, text = choice
        notes.append(f"Основатель выбрал пункт {number} из твоего прошлого ответа: «{text}». Развивай именно его, "
                     "шаг за шагом: кто первый клиент этой версии, что минимально сделать и как проверить за неделю. "
                     "Все варианты заново не перечисляй. Один вопрос в конце.")
    if RULES_REQUEST_RE.search(latest):
        notes.append("ВНИМАНИЕ: основатель просит поменять твои правила или поставить баллы. Первой фразой "
                     "спокойно откажи: баллы ставит таблица по фактам из рассказа, ты их не меняешь.")
    if APPROVAL_RE.search(latest):
        notes.append("ВНИМАНИЕ: основатель ссылается на чужое одобрение. Не называй это хорошим знаком и не "
                     "поздравляй. Спроси, что именно обещано и чем подтверждено: договор, оплата, письмо, дата.")
    # Бруно всегда на «вы»: так он не угадывает пол («вы сделали») и звучит уважительно.
    notes.append("Обращайся к основателю строго на «вы», даже если он пишет на «ты»: «вам», «ваш», "
                 "«расскажите», «попробуйте», «вы сделали». Ни одного «ты».")
    last = messages[-1]["content"].strip() if messages[-1]["role"] == "user" else ""
    streak = disengaged_streak(messages)
    recent_replies = [m["content"] for m in messages[-6:] if m["role"] == "assistant"]
    offered_pause = any(PAUSE_OFFER_RE.search(text) for text in recent_replies[-3:])
    if streak >= DISENGAGED_STREAK and offered_pause:
        notes.append(f"Основатель отвечает односложно уже {streak} раз подряд, а паузу ты уже предлагал. "
                     "Не повторяй итог и вопрос «сейчас или позже». Ответь одной-двумя фразами: один "
                     "конкретный шаг на сегодня и что написать тебе, когда будет результат. Без вопроса "
                     "и без похвалы.")
    elif streak >= DISENGAGED_STREAK:
        notes.append(f"Основатель отвечает односложно уже {streak} раз подряд. Не давай новых "
                     "заданий и советов. Подведи итог разговора в одном-двух предложениях обычным "
                     "текстом, без списка и тире, и спроси, продолжить сейчас или вернуться позже.")
