def wants_review(text):
    return bool(REVIEW_RE.search(text or ""))


def prefers_formal(messages):
    """Основатель обращается на «вы» в последних репликах и ни разу на «ты»."""
    recent = " ".join(m["content"] for m in messages[-8:] if m["role"] == "user")
    return bool(FORMAL_RE.search(recent)) and not INFORMAL_RE.search(recent)


def wants_long_answer(text):
    """Основатель просит разбор, план, совет или текст: короткий ответ не подойдёт."""
    return bool(LONG_ANSWER_RE.search(text or ""))


