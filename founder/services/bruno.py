QUESTION_RE = re.compile(r"[^.!?\n]*\?")
OPENER_RE = re.compile(
    r"^\s*(?:Отличн\w*|Прекрасн\w*|Замечательн\w*|Великолепн\w*|Хорош\w*)\s+"
    r"(?:вопрос|идея|мысль|уточнение)\s*[!.,]\s*"
    r"|^\s*(?:Конечно|Безусловно|Разумеется)\s*[!,.]\s*",
    re.IGNORECASE,
)
AI_DISCLAIMER_RE = re.compile(
    r"(?:Как (?:языковая модель|искусственный интеллект|ИИ|AI)[^.!?]*[.!?]\s*)",
    re.IGNORECASE,
)


def founder_name(startup):
    owner = getattr(startup, "owner", None)
    name = (getattr(owner, "display_name", "") or getattr(owner, "first_name", "") or "").strip()
    return name.split()[0][:40] if name else ""


def conversation_notes(messages):
    """Подсказки о ходе беседы: что уже обсуждали и какие вопросы звучали."""
    if not messages:
        return ""
    founder_text = " ".join(m["content"] for m in messages if m["role"] == "user").lower()
    founder_turns = sum(1 for m in messages if m["role"] == "user")
    covered = [axis for axis, pattern in AXIS_HINTS.items() if re.search(pattern, founder_text)]
    missing = [axis for axis in AXIS_HINTS if axis not in covered]

    asked = []
    for message in messages[:-1]:
        if message["role"] == "assistant":
            asked.extend(q.strip() for q in QUESTION_RE.findall(message["content"]))
    asked = [q for q in asked if len(q) > 12][-6:]

    notes = [f"Ход беседы: основатель ответил {founder_turns} раз(а)."]
    if covered:
        notes.append("Уже звучало: " + ", ".join(covered) + ".")
    if missing:
        notes.append("Ещё не обсуждали: " + ", ".join(missing)
                     + ". Переходи к ним плавно, когда текущая тема исчерпана.")
    if asked:
        notes.append("Ты уже спрашивал (не повторяй дословно и по смыслу, "
                     "если ответ уже получен): " + " | ".join(asked))
    last = messages[-1]["content"].strip() if messages[-1]["role"] == "user" else ""
    if last and len(last) < 25:
        notes.append("Последний ответ короткий: не дави, помоги примером или вариантами.")
    proposed_table = any("Составить таблицу" in m["content"] for m in messages if m["role"] == "assistant")
    if founder_turns >= 6 and len(covered) >= 4 and not proposed_table:
        notes.append("Картины уже достаточно: в этом ответе можно один раз предложить "
                     "нажать «Составить таблицу», чтобы увидеть радар.")
    return "\n".join(notes)


def tidy_reply(text):
    """Убрать дежурные вступления и отговорки «как ИИ» из готового текста."""
    cleaned = AI_DISCLAIMER_RE.sub("", text)
    stripped = OPENER_RE.sub("", cleaned, count=1)
    if stripped.strip():
        cleaned = stripped[:1].upper() + stripped[1:]
    cleaned = re.sub(r"^#{1,6}\s*", "", cleaned, flags=re.MULTILINE)
    return cleaned


def tidy_stream(chunks, head_size=80):
    """Потоковая версия tidy_reply: чистит начало ответа, остальное отдаёт сразу."""
    head = ""
    flushed = False
    for chunk in chunks:
        if flushed:
            yield chunk
            continue
        head += chunk
        if len(head) >= head_size or (len(head) >= 40 and re.search(r"[.!?]\s", head[30:])):
            flushed = True
            cleaned = tidy_reply(head)
            if cleaned:
                yield cleaned
    if not flushed and head:
        yield tidy_reply(head)
