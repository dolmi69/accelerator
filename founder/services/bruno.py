def _first_question(sentence):
    """Из «вопроса и ещё вопроса» оставить первый, если он и сам по себе вопрос."""
    match = DOUBLE_QUESTION_RE.search(sentence)
    if not match or len(sentence[:match.start()].strip()) < DOUBLE_QUESTION_MIN_HEAD:
        return sentence
    ending = sentence[len(sentence.rstrip()):]
    closing = re.search(r"\?[»\")]*$", sentence.rstrip())
    return sentence[:match.start()].rstrip(" ,") + (closing.group() if closing else "?") + ending


