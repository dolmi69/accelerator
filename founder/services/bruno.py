def style_issues(text, *, long_form=False, pitch=False, gender=None, self_female=False):
    """Замечания к ответу для прогонов bruno_eval и тестов."""
    issues = []
    lowered = text.lower()
    # «Кто клиент? Или это родители?» — один вопрос с вариантами.
    questions = text.count("?") - len(re.findall(r"\?\s*(?:Или|А может)\b[^?]*\?", text))
    if not long_form and questions > 1:
        issues.append(f"вопросов: {questions}")
    if long_form and questions > 2:
        issues.append(f"вопросов в развёрнутом ответе: {questions}")
    limit = 2200 if long_form else (450 if pitch else 600)
    if len(text) > limit:
        issues.append(f"длина {len(text)} > {limit}")
    if not long_form and re.search(r"^\s*(?:[-*•]|\d+[.)])\s", text, re.MULTILINE):
        issues.append("список в коротком ответе")
    if "**" in text or re.search(r"^#{1,6}\s", text, re.MULTILINE):
        issues.append("markdown-разметка")
    dashes = text.count("—")
    if dashes > (3 if long_form else 1):
        issues.append(f"тире: {dashes}")
    found = [phrase for phrase in SLOP_PHRASES if re.search(r"(?<!\w)" + re.escape(phrase) + r"(?!\w)", lowered)]
    if found:
        issues.append("штампы: " + ", ".join(found))
    # Род основателя известен из его же слов: тогда «ты решил» или «ты решила» уместны.
    gendered = GENDERED_YOU_RE.search(text) if gender is None else None
    if gendered:
        issues.append(f"угадан род: «{gendered.group()}»")
    informal = INFORMAL_RE.search(text)
    if informal:
        issues.append(f"на «ты»: «{informal.group()}»")
    if re.search(r"(?<!\w)Привет(?!\w)", text):
        issues.append("приветствие «Привет» вместо «Здравствуйте»")
    if not self_female and re.search(r"(?<!\w)(?:Рада|я рада)(?!\w)", text):
        issues.append("Бруно о себе в женском роде")
    last_sentence = re.split(r"(?<=[.!?…])\s+", text.strip())[-1] if text.strip() else ""
    if GENERIC_CLOSER_RE.fullmatch(last_sentence):
        issues.append(f"пустая концовка: «{last_sentence}»")
    if text.startswith("[ОШИБКА]"):
        issues.append("ошибка провайдера")
    return issues


def _claim(text):
    """Тема и знак утверждения: «нет клиентов» против «12 клиентов»."""
    lowered = text.lower()
    negative, numeric = bool(NEGATION_RE.search(lowered)), bool(re.search(r"\d", lowered))
    # Планы («хотим 100 клиентов») не спорят с фактами («клиентов пока нет»).
    if negative == numeric or PLAN_RE.search(lowered):
        return set(), None
    topics = {name for name, pattern in CLAIM_TOPICS.items() if re.search(pattern, lowered)}
    return topics, "negative" if negative else "numeric"


def contradiction(messages):
    """Найти прежнюю реплику основателя, которая спорит с последней."""
    if not messages or messages[-1]["role"] != "user":
        return None
    topics, sign = _claim(messages[-1]["content"])
    if not sign:
        return None
    for message in reversed(messages[:-1]):
        if message["role"] != "user":
            continue
        old_topics, old_sign = _claim(message["content"])
        if old_sign and old_sign != sign and topics & old_topics:
            return message["content"].strip()[:200]
    return None


NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)?")
# «клиент остаётся 4 месяца», «маржа 25%» — не число клиентов: иначе Бруно видел «140 → 4».
DURATION_AFTER_RE = re.compile(r"\s*(?:%|мес|дн|день|дня|недел|год|лет|час|мин|раз(?:а)?\b)")
MONEY_AFTER_RE = re.compile(r"\s*(?:₽|руб|р\b|тыс|млн|к\b)")


def _topic_numbers(text):
    """Тема → ближайшее к её слову число: «платят 15 человек» → {"клиенты": "15"}."""
    lowered = text.lower()
    if PLAN_RE.search(lowered):
        return {}
    found = {}
    counts = [number for number in NUMBER_RE.finditer(lowered) if not DURATION_AFTER_RE.match(lowered, number.end())]
    for name, pattern in CLAIM_TOPICS.items():
        # Суммы денег — числа для продаж, но не для числа клиентов или людей в команде.
        numbers = counts if name == "продажи" else [
            number for number in counts if not MONEY_AFTER_RE.match(lowered, number.end())]
        for match in re.finditer(pattern, lowered):
            near = [(min(abs(number.start() - match.end()), abs(match.start() - number.end())), number.group())
                    for number in numbers]
            near = [item for item in near if item[0] <= 20]
            if near:
                found.setdefault(name, min(near)[1])
    return found


def number_change(messages):
    """(тема, было, стало, цитата), если основатель назвал по той же теме другое число."""
    if not messages or messages[-1]["role"] != "user":
        return None
    latest = _topic_numbers(messages[-1]["content"])
    for message in reversed(messages[:-1]):
        if message["role"] != "user":
            continue
        for topic, old in _topic_numbers(message["content"]).items():
            new = latest.get(topic)
            if new and new != old:
                return topic, old, new, message["content"].strip()[:160]
    return None


