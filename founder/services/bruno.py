# «Привет» в начале ответа меняем на «Здравствуйте»: Бруно всегда на «вы».
GREETING_RE = re.compile(r"(?<!\w)Привет(?!\w)")


def _keep_case(original, replacement):
    return replacement[:1].upper() + replacement[1:] if original[:1].isupper() else replacement


def _plural_imperative(word):
    # «займись» → «займитесь», «постарайся» → «постарайтесь», «попробуй» → «попробуйте».
    if word.lower().endswith(("ся", "сь")):
        return word[:-2] + "тесь"
    return word + "те"


def to_formal(sentence):
    """Перевести обращение на «ты» в «вы». Бруно всегда на «вы», это страховка к промпту."""
    sentence = GREETING_RE.sub("Здравствуйте", sentence)
    sentence = YOU_PAST_FORMAL_RE.sub(
        lambda m: _keep_case(m.group(1), "вы") + m.group(2) + m.group(3) + "и" + ("сь" if m.group(4) else ""),
        sentence)
    sentence = YOU_SHORT_RE.sub(lambda m: _keep_case(m.group(1), "вы") + m.group(2) + YOU_SHORT[m.group(3)], sentence)
    for pattern, replacement in VERB_2SG_SPECIAL:
        sentence = pattern.sub(replacement, sentence)
    sentence = VERB_2SG_RE.sub(lambda m: m.group(1) + m.group(2) + ("тесь" if m.group(3) else "те"), sentence)
    sentence = YOU_PRONOUN_RE.sub(lambda m: _keep_case(m.group(1), YOU_PRONOUNS[m.group(1).lower()]), sentence)
    return YOU_IMPERATIVE_RE.sub(lambda m: _plural_imperative(m.group(1)), sentence)


def _fix_phrases(sentence, self_male=True):
    for pattern, replacement in PHRASE_FIXES + (MALE_SELF_FIXES if self_male else ()):
        sentence = pattern.sub(replacement, sentence)
    return THINK_PREFIX_RE.sub(lambda match: match.group(1).upper(), sentence)


def _limit_dashes(sentence, dashes_seen):
    """Одно тире на ответ можно (правило стиля), следующие одиночные — в двоеточие.

    Парные тире вокруг вставки не трогаем: двоеточие их сломает.
    """
    # «— пункт» в начале строки — маркер списка, а не тире: показываем точкой списка.
    sentence = LIST_DASH_RE.sub(r"\1• ", sentence)
    found = len(DASH_RE.findall(sentence))
    if dashes_seen and found == 1 and ":" not in sentence:
        sentence = DASH_RE.sub(": ", sentence)
    return sentence, dashes_seen + found


def polish_stream(chunks, *, single_question=True, gender=None, self_male=True, formal=True, asked=(),
                  keep_first=False):
    """Правка по предложениям без отказа от потоковой выдачи.

    Исправляет частые штампы и, если нужен один вопрос, из двух вопросов подряд
    оставляет последний: GigaChat часто пишет «Что выберешь? Какая задача главная?».
    Вопрос задерживается только до начала следующего предложения. Последний вопрос,
    который по сути повторяет заданный раньше (asked), отбрасывается.
    """
    from founder.services.mentor import repeats_question

    # held — последний вопрос, trail — утверждения после него. Вопрос в середине ответа держим,
    # пока не ясно, будет ли ещё один: «Что сработало? Это покажет канал. Сколько вы потратили?»
    # раньше давало два вопроса, теперь остаётся последний.
    buffer, held, trail, emitted, dashes = "", "", "", False, 0

    def process(sentence):
        nonlocal held, trail, dashes
        sentence = to_formal(sentence) if formal else sentence
        sentence, dashes = _limit_dashes(_fit_gender(_fix_phrases(sentence, self_male), gender), dashes)
        is_question = sentence.rstrip().rstrip("»\")").endswith("?")
        if not single_question:
            return sentence
        if not is_question:
            if not held:
                return sentence
            trail += sentence
            if len(trail) > HELD_TRAIL_LIMIT:
                # Длинный хвост после вопроса не держим: поток не должен замирать надолго.
                out, held, trail = held + trail, "", ""
                return out
            return ""
        sentence = _first_question(sentence)
        if held and not trail and re.match(r"\s*(?:Или|А может)\b", sentence):
            # «Кто клиент? Или это родители?» — один вопрос с вариантами, а не два.
            held += sentence
            return ""
        if held and trail:
            # Вопрос, потом утверждения, потом новый вопрос: первый вопрос убираем, утверждения отдаём.
            # Короткий риторический вопрос с ответом («Зачем? Чтобы проверить спрос.») оставляем.
            # При противоречии главный вопрос первый («Это рост или поправка?»): тогда убираем новый.
            rhetorical = len(held.strip()) < RHETORICAL_QUESTION
            if keep_first and not rhetorical:
                out, held, trail = held + trail, "", ""
                return out
            out = held + trail if rhetorical else held[:len(held) - len(held.lstrip())] + trail.lstrip()
            held, trail = sentence, ""
            return out
        if held and keep_first:
            return ""
        if held and (GENERIC_CLOSER_RE.fullmatch(sentence.strip()) or re.match(r"\s*(?:И|А\s+ещё|Также)\s", sentence)
                     or (len(sentence.strip()) < SELF_CONTAINED_QUESTION and QUESTION_WORD_RE.match(sentence))):
            # «Как будете привлекать? Согласны попробовать?» — вопрос уже есть, пустая концовка не нужна.
            # «Сколько клубов в городе? И какой средний размер?» — второй вопрос, первый оставляем.
            return ""
        if held and len(sentence.strip()) >= SELF_CONTAINED_QUESTION:
            # Сохраняем переносы строк перед отброшенным вопросом.
            held = held[:len(held) - len(held.lstrip())] + sentence
        else:
            held += sentence
        return ""

    for chunk in chunks:
        buffer += chunk
        while (match := SENTENCE_END_RE.search(buffer)):
            sentence, buffer = buffer[:match.end()], buffer[match.end():]
            out = process(sentence)
            if out:
                emitted = True
                yield out
    tail = process(buffer) if buffer else ""
    if held and (emitted or trail.strip()) and (GENERIC_CLOSER_RE.fullmatch(held.strip())
                                               or repeats_question(held, asked)):
        # Пустая концовка вроде «Начнём?» или вопрос, который уже звучал: ответ лучше без неё.
        prefix, held = held[:len(held) - len(held.lstrip())], ""
        trail = prefix + trail.lstrip() if trail else ""
    if not single_question and emitted and (GENERIC_CLOSER_RE.fullmatch(tail.strip())
                                            or (tail.strip().endswith("?") and repeats_question(tail, asked))):
        # В развёрнутом ответе последняя фраза приходит без пробела после неё. Вопрос, который уже
        # звучал («Сколько сочинений проверил каждый?» через два хода), тоже убираем.
        tail = ""
    elif not single_question and emitted:
        last = re.split(r"(?<=[.!?…])\s+", tail.strip())
        if len(last) > 1 and GENERIC_CLOSER_RE.fullmatch(last[-1]):
            tail = tail.strip()[:-len(last[-1])].rstrip() + " "
    if tail or held or trail:
        yield tail + held + trail


def tidy_stream(chunks, head_size=80):
    """Потоковая версия tidy_reply: чистит начало ответа, остальное отдаёт сразу."""
    head = ""
    flushed = False
    for chunk in _strip_bold(chunks):
        if flushed:
            yield chunk
            continue
        head += chunk
        if len(head) >= head_size or (len(head) >= 40 and re.search(r"[.!?]\s", head[30:])):
            flushed = True
            cleaned = tidy_reply(head)
            if cleaned:
                yield cleaned
    if not flushed and head:
        yield tidy_reply(head)
