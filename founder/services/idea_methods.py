"""Методы Мастерской идей: приёмы, ловушки и вопросы оценки идеи.

Принципы пересказаны своими словами, текст источников в промпты не копируется
(как с книгой Р. Абрамс у Бруно-наставника). Откуда что взято:

- Пол Грэм, «How to Get Startup Ideas» (2012, прочитано 2026-10-14): ищите проблемы, а не идеи;
  «колодец» (немногим нужно очень сильно) лучше «лужи» (многим немного); «ситкомные» идеи звучат
  правдоподобно, но никому не нужны срочно; скучные и муторные задачи недооценены; конкуренты не
  повод бросать, если есть тезис, что они упускают; замена приходит сбоку, по другой оси;
  сначала продайте, потом стройте.
- Джаред Фридман (YC), «How to Get and Evaluate Startup Ideas» (по конспектам доклада): ошибки
  «решение ищет проблему» и «смоляная яма» (все пробуют годами, мешает скрытая структурная
  причина); 10 вопросов оценки: подходит ли команде, острота боли, конкуренты и что они упускают,
  нужно ли самому и знакомым, что изменилось недавно, есть ли прокси (модель сработала в другом
  месте), не превращается ли в услугу, где каждый клиент — часы основателя; рецепты: что изменилось,
  вариант успешной модели для другого места или клиента, сломанная большая отрасль.
- «Стратегия голубого океана» (Ким, Моборн): сетка «убрать, снизить, повысить, создать»; пути
  поиска: альтернативные отрасли, цепочка покупателей (кто платит, кто пользуется, кто влияет),
  дополняющие товары и услуги (что клиент делает до и после), функциональное ↔ эмоциональное.
- «Разработка ценностных предложений» (Остервальдер): работы клиента (функциональные, социальные,
  эмоциональные), его боли и желаемые выгоды.
- «Спроси маму» (Р. Фитцпатрик): спрашивать о прошлом опыте человека, а не о своей идее;
  комплименты и «я бы купил» не данные; успех — обязательство: время, репутация, деньги.
- ТРИЗ (Альтшуллер) и «Thinkertoys» (Михалко, SCAMPER): идеальный конечный результат (функция
  выполняется сама, без лишнего звена), перевернуть, соединить, приспособить, убрать.
"""

