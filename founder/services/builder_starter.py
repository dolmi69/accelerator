"""Editable, asset-free introduction to Studio. Used only for a new draft."""
import uuid

from founder.services import free_canvas


def build_document():
    from founder.services.visual_builder import THEME, new_block

    def block(kind, *, anchor=None, surface='base', **props):
        result = new_block(kind)
        result['props'].update(props)
        result['style']['surface'] = surface
        if anchor:
            result['id'] = anchor
        return result

    def nav():
        return block('nav', brand='Bruno Studio', button='Как начать', link='/guide/', items=[
            {'title': 'Главная', 'link': '/'}, {'title': 'Возможности', 'link': '/features/'}])

    def footer():
        return block('footer', brand='Bruno Studio', text='Ваш сайт. Ваши страницы. Ваши правила.', items=[
            {'title': 'Главная', 'link': '/'}, {'title': 'Возможности', 'link': '/features/'},
            {'title': 'Как начать', 'link': '/guide/'}])

    def page(title, slug, description, blocks):
        return {'id': uuid.uuid4().hex, 'title': title, 'slug': slug,
                'description': description, 'blocks': blocks}

    home = page('Главная', '', 'Познакомьтесь с конструктором Bruno Studio и соберите свой сайт.', [
        nav(),
        block('hero', eyebrow='МЕСТО ДЛЯ ВАШЕЙ ИДЕИ',
              title='Соберите сайт.\nРасскажите свою историю.',
              text='Создавайте свои страницы, добавляйте блоки и изображения. Двигайте элементы как удобно и меняйте каждую деталь прямо на холсте.',
              button='Посмотреть возможности', link='/features/'),
        block('features', anchor='features', eyebrow='ОТ ЗАМЫСЛА К САЙТУ',
              title='Всё начинается с вашей идеи.',
              text='Лендинг продукта, портфолио, страница услуги или небольшой сайт с несколькими разделами.', items=[
                  {'title': 'Готовые блоки', 'text': 'Первый экран, галерея, отзывы, тарифы и вопросы. Добавляйте нужное и меняйте порядок.'},
                  {'title': 'Свободное размещение', 'text': 'Ставьте тексты, картинки и кнопки в любом месте внутри свободного блока. Настраивайте размер, цвет и слои.'},
                  {'title': 'Ссылка на результат', 'text': 'Проверьте вид на телефоне и компьютере, сохраните версию и опубликуйте сайт в BrunoHost.'}]),
        block('text', anchor='about', eyebrow='ЭТО УЖЕ ВАШ САЙТ',
              title='Этот шаблон можно менять целиком.',
              text='Вы сейчас видите обычный редактируемый сайт. Нажмите на заголовок, замените текст или картинку, добавьте страницу слева. Всё, что есть в шаблоне, собрано теми же инструментами, которые доступны вам.'),
        block('cta', surface='white', eyebrow='ПОПРОБУЙТЕ САМИ',
              title='Начните с одной детали.',
              text='Поменяйте заголовок на этой странице. Затем откройте обзор возможностей и попробуйте свободный блок.',
              button='К примеру свободного блока', link='/features/#free-layout'),
        footer(),
    ])

    free = block('canvas', anchor='free-layout')
    free['props'] = {'height': 480, 'mobileHeight': 620, 'elements': []}

    def element(kind, content, desktop, mobile, **style):
        result = free_canvas.new_element(kind)
        result['content'].update(content)
        for device, box in [('desktop', desktop), ('mobile', mobile)]:
            x, y, width, height, font_size = box
            result[device].update(x=x, y=y, width=width, height=height, fontSize=font_size)
        result['style'].update(style)
        free['props']['elements'].append(result)

    element('shape', {}, (48, 24, 1024, 408, 20), (20, 20, 350, 580, 20),
            background='#eaf3f0', radius=24)
    element('text', {'text': 'Это свободный блок'}, (84, 68, 530, 32, 16), (44, 52, 302, 30, 16),
            color=THEME['accent'], fontWeight='600')
    element('text', {'text': 'Двигайте элементы.\nМеняйте всё под себя.'},
            (84, 124, 570, 140, 48), (44, 112, 302, 130, 28),
            color=THEME['ink'], fontWeight='600')
    element('text', {'text': 'Текст, кнопка и иллюстрация здесь независимы.\nВыберите любой элемент и попробуйте его передвинуть.'},
            (84, 278, 550, 58, 18), (44, 260, 302, 80, 16), color=THEME['ink'])
    element('button', {'text': 'Открыть инструкцию', 'link': '/guide/'},
            (84, 354, 260, 54, 16), (44, 358, 302, 54, 16))
    element('art', {}, (730, 100, 280, 280, 20), (120, 432, 150, 150, 20))

    features = page('Возможности', 'features', 'Страницы, готовые блоки, свободное размещение, изображения и публикация.', [
        nav(),
        block('hero', eyebrow='КОНСТРУКТОР В ДЕЛЕ', title='Собирайте блоками.\nНастраивайте свободно.',
              text='Используйте готовые секции там, где важна скорость. Добавляйте свободный блок там, где хотите сами решить, как будет выглядеть каждая деталь.',
              button='Попробовать свободный блок', link='#free-layout'),
        block('features', surface='white', eyebrow='ВАШИ ИНСТРУМЕНТЫ', title='Вы управляете содержимым и видом.',
              text='Работайте с целой страницей или с одним элементом.', items=[
                  {'title': 'Несколько страниц', 'text': 'Создавайте страницы со своими адресами. Связывайте их меню и кнопками, копируйте и переставляйте блоки.'},
                  {'title': 'Ваши изображения', 'text': 'Загружайте PNG, JPG и WebP в библиотеку проекта или вставляйте скриншот прямо из буфера.'},
                  {'title': 'Привычная вставка', 'text': 'Ctrl/⌘V распознаёт текст, картинку и ссылку. На холсте появляется подходящий элемент.'}]),
        free,
        block('features', eyebrow='ДЕТАЛИ ПОД ВАШ КОНТРОЛЕМ', title='От положения до последней правки.', text='', items=[
            {'title': 'Оформление и слои', 'text': 'Меняйте цвета, размер, шрифт и скругления. Размещайте элементы друг над другом, скрывайте или закрепляйте их.'},
            {'title': 'Компьютер и телефон', 'text': 'У свободного блока отдельное положение элементов для двух экранов. Можно автоматически собрать версию для телефона и довести её вручную.'},
            {'title': 'Сохранение и отмена', 'text': 'Черновик сохраняется автоматически. Отменяйте правки, сохраняйте версии или скачивайте сайт со всеми страницами.'}]),
        footer(),
    ])

    guide = page('Как начать', 'guide', 'Короткая инструкция: редактирование, вставка, просмотр и публикация сайта.', [
        nav(),
        block('hero', eyebrow='ПЕРВЫЕ ШАГИ', title='От первого изменения\nдо ссылки на сайт.',
              text='Начните с этого шаблона. Замените содержимое на своё и оставьте только те страницы и блоки, которые нужны вашему проекту.',
              button='Вернуться к шаблону', link='/'),
        block('features', surface='white', eyebrow='ТРИ ПРОСТЫХ ШАГА', title='Создайте, проверьте, поделитесь.', text='', items=[
            {'title': 'Соберите', 'text': 'Выберите страницу слева. Добавьте блок через кнопку «Добавить блок» или создайте новую страницу. Блоки можно перетаскивать в списке.'},
            {'title': 'Настройте', 'text': 'Нажмите на текст и меняйте его прямо на странице. Выберите блок или элемент, чтобы открыть настройки справа. Проверьте режим «Телефон».'},
            {'title': 'Опубликуйте', 'text': 'Откройте «Просмотр» и проверьте переходы. Кнопка «Опубликовать» сохранит версию и выдаст ссылку BrunoHost.'}]),
        block('text', eyebrow='ВСТАВЛЯЙТЕ КАК ПРИВЫКЛИ', title='Скопировали. Вставили. Готово.',
              text='Нажмите на нужное место свободного блока и используйте Ctrl+V или ⌘V. Текст станет текстовым элементом, картинка сохранит пропорции, а ссылка станет кнопкой. Если свободного блока ещё нет, он появится после выбранного обычного блока. Внутри текстового поля вставка работает как обычно.'),
        block('faq', eyebrow='ПОЛЕЗНО ЗНАТЬ', title='Ответы перед первым запуском.', items=[
            {'title': 'Нужно ли знать код?', 'text': 'Для страниц, текстов, изображений, кнопок и оформления код не требуется. Все элементы этого шаблона можно менять в редакторе.'},
            {'title': 'Как вернуть случайно удалённый элемент?', 'text': 'Нажмите кнопку отмены сверху или Ctrl/⌘Z. Пока вкладка открыта, можно отменить последние действия и вернуть их повтором.'},
            {'title': 'Чем черновик отличается от публикации?', 'text': 'Автосохранение хранит правки в редакторе. На опубликованный сайт они попадут после следующего нажатия «Опубликовать».'},
            {'title': 'Можно ли доработать сайт вместе с Бруно?', 'text': 'Сохраните версию, вернитесь в лабораторию и опишите изменения Бруно. Для сайта из конструктора он работает со страницами, блоками и элементами.'}]),
        block('cta', surface='white', eyebrow='ТЕПЕРЬ ВАША ОЧЕРЕДЬ', title='Сделайте этот сайт своим.',
              text='Начните с заголовка, своей картинки или нового блока. Всё остальное можно изменить по ходу работы.',
              button='На главную страницу', link='/'),
        footer(),
    ])
    return {'schema': 1, 'theme': dict(THEME), 'pages': [home, features, guide]}
